/**
 * Экранирует запятые ВНУТРИ имени категории бэкслешем (`,` → `\,`) для колонки
 * `Categories` импортёра WooCommerce.
 *
 * Импортёр трактует неэкранированную запятую как разделитель НЕСКОЛЬКИХ
 * категорий, а ` > ` — как уровень вложенности. Поэтому имя вроде «Джемперы,
 * свитеры и кардиганы» без экранирования дробится на две категории, и фрагмент
 * после запятой теряет родителя (см. woocommerce/woocommerce#16192). Бэкслеш —
 * официальный механизм импортёра, чтобы запятая осталась частью имени.
 *
 * Работает на уровне ОДНОГО имени: разделитель уровней ` > ` и запятые между
 * разными категориями (если товару назначено несколько) экранировать не нужно —
 * этим занимается вызывающий код через `.join(" > ")` / `.join(",")`.
 *
 * Идемпотентна: запятую, перед которой уже стоит бэкслеш, повторно не трогаем,
 * поэтому повторный прогон не порождает `\\,`.
 */
export function escapeCategoryName(name: string): string {
  return name.replace(/(?<!\\),/g, "\\,");
}
